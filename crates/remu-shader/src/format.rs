#[cfg(test)]
mod tests {
    use super::decode_unified_format;

    #[test]
    fn preserves_sparse_and_image_only_unified_formats() {
        assert_eq!(decode_unified_format(0), Some((0, 0)));
        assert_eq!(decode_unified_format(60), Some((10, 4)));
        assert_eq!(decode_unified_format(131), Some((131, 7)));
        assert_eq!(decode_unified_format(170), Some((170, 9)));
        assert_eq!(decode_unified_format(30), None);
        assert_eq!(decode_unified_format(183), None);
    }
}
